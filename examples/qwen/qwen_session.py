#!/usr/bin/env python3
"""The forward pass of Qwen2 in a session of .chx kernels (docs/resident.md section 20; roadmap M7.1). qwen_ref.py is its specification (binary64 numpy).

    python3 examples/qwen/qwen_session.py WEIGHTS_DIR SESSION_DIR     # writes the session of Qwen2.5-0.5B for the fixed batch (examples/qwen/data.py)

Mixed precision on the matrix unit: the weights and the activations that enter a product are f16, every product accumulates in f32, the residual stream is f32. Per block 16 kernels:
RMSNorm (rms_h), the fused q/k/v product with its bias and rotary embedding (rope_g*, bias_rep), attention (att_s, att_sm, att_o, unheads), the o projection and residual (res_add),
RMSNorm, the fused gate/up product, SwiGLU (swiglu_h), the down projection and residual. After the last block: RMSNorm, the tied output product, and the cross-entropy as three kernels
(ce_stats, ce_comb) with no `max a b`. A request is `1` (one forward pass); the answer is the loss of each of the n positions and the 1-based arg max of its logits.

Grouped-query attention (14 query heads over 2 key/value heads of 64, a head's group being h / 7, a division the surface forbids): the key and value heads are written once per query
head of their group by the kernel that rotates them (`group` stores of the same tile), in a heads-major layout [sequence, head, position, 64] shared with q, so that every attention
kernel has the one grid coordinate p = sequence * heads + head and every offset stays affine. The alternative, a loop over the group inside the kernel, is measured in section 20."""
import math
import os
import subprocess
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import qwen_ref as R  # noqa: E402


def block(n, cap):
    return next(b for b in range(min(n, cap), 0, -1) if n % b == 0)


def put(path, values, dtype="<f4"):
    with open(path, "wb") as f:
        f.write(np.asarray(values, dtype=dtype).reshape(-1).tobytes())


def write_files(directory, c, P):
    """The weight files convert.py writes, from a parameter dict (used by the tests, which have random models)."""
    os.makedirs(directory, exist_ok=True)
    for name, w in P.items():
        small = name.split(".")[-1] in ("ln1", "ln2", "norm", "bqkv")
        put(os.path.join(directory, f"{name}.{'f32' if small else 'f16'}"), w, "<f4" if small else "<f2")


def rope_source(name, group, rotate):
    """A kernel that adds the bias to a block of columns of the fused projection, rotates it (the 'rotate half' pairs) when `rotate`, rounds to f16 and writes it to `group` heads of the
    heads-major output: group 1 for the query heads, the group size for the key and value heads."""
    stores = []
    for g in range(group):
        row = f"((b * nh + h) * {group} + {g}) * t + i * bm"
        amp = "&" if g < group - 1 else ""
        if rotate:
            stores += [f"  let lh{g} = stage f16 {amp}lo", f"  let hh{g} = stage f16 {amp}hi", f"  store lh{g} -> y[{row}, 0]", f"  store hh{g} -> y[{row}, hf]"]
        else:
            stores += [f"  let vh{g} = stage f16 {amp}a1", f"  store vh{g} -> y[{row}, 0]"]
    if rotate:
        body = f"""  let x1 = load qkv[b * t + i * bm, c0 + h * hf * 2 ; bm, hf]
  let x2 = load qkv[b * t + i * bm, c0 + h * hf * 2 + hf ; bm, hf]
  let b1 = load bias[0, c0 + h * hf * 2 ; 1, hf]
  let b2 = load bias[0, c0 + h * hf * 2 + hf ; 1, hf]
  let a1 = x1 + b1
  let a2 = x2 + b2
  let cc = load cs[i * bm, 0 ; bm, hf]
  let ss = load sn[i * bm, 0 ; bm, hf]
  let p1 = &a1 * &cc
  let p2 = &a2 * &ss
  let lo = p1 - p2
  let p3 = a2 * cc
  let p4 = a1 * ss
  let hi = p3 + p4
""" + "\n".join(stores)
    else:
        body = f"""  let x1 = load qkv[b * t + i * bm, c0 + h * hf * 2 ; bm, hf * 2]
  let b1 = load bias[0, c0 + h * hf * 2 ; 1, hf * 2]
  let a1 = x1 + b1
""" + "\n".join(stores)
    ins = "  in  cs:   f32[t, hf]\n  in  sn:   f32[t, hf]\n" if rotate else ""
    return f"""// {'Rotary embedding' if rotate else 'Bias'} of the columns c0 .. c0 + nh 2 hf of the fused q/k/v product, written f16 to {group} head{'s' if group > 1 else ''} of the heads-major
// output [nb nh {group} t, 2 hf] for every source head (generated by qwen_session.rope_source; docs/resident.md section 20).
algo {name}(nb, nh, t, w, c0, bm, hf)
  in  qkv:  f32[nb * t, w]
  in  bias: f32[1, w]
{ins}  out y:    f16[nb * nh * {group} * t, 2 * hf]
{{
  grid b over nb, h over nh, i over t / bm
{body}
}}

schedule {name} for apple-m-series {{ threads 128 }}
schedule {name} for nvidia-ada     {{ threads 128 }}
"""


def write(directory, c, wdir, tokens, acts=None, tune=None, eps_override=None):
    """Writes the session for the batch `tokens` ([nb, t]) over the weight files of `wdir`; answers the path of the session file. With `acts` (a path), the residual stream after
    every block is saved there (f32, [n, d] one after another, written on the request `checkpoint`)."""
    os.makedirs(directory, exist_ok=True)
    p = lambda name: os.path.join(directory, name)
    w = lambda name: os.path.abspath(os.path.join(wdir, name))
    n, d, h, hkv, dh, ff, v, t, nb, ll = c.n, c.d, c.h, c.hkv, c.dh, c.ff, c.v, c.t, c.nb, c.layers
    grp, dkv, hf = c.group, c.dkv, c.dh // 2
    assert dh % 32 == 0 and d % 64 == 0 and t % 64 == 0 and n % 64 == 0 and (d + 2 * dkv) % 64 == 0 and ff % 64 == 0 and h % hkv == 0 and dh == d // h
    tokens = np.asarray(tokens)
    assert tokens.shape == (nb, t)
    tn = dict(bc=2304, ebm=1, abm=2, rbm=8, cbm=8, sbm=1, sbc=block(ff, 256), gemm_sched={}, attn=dict(threads=128, warps="2 2", bm=64, bn=64, bk=32),
              ao=dict(threads=128, warps="2 2", bm=64 if dh <= 64 else 32, bk=32))
    tn.update(tune or {})
    tok = tokens.reshape(-1)
    emb = np.fromfile(w("emb.f16"), dtype="<f2").reshape(-1, d)[:v]
    put(p("x0"), emb[tok].astype(np.float32))
    ang = np.arange(t)[:, None] * c.theta ** (-np.arange(hf) / hf)[None, :]
    put(p("cos"), np.cos(ang))
    put(p("sin"), np.sin(ang))
    put(p("mask"), np.triu(np.full((t, t), -1e9), 1))
    bc = min(tn["bc"], -(-v // 128) * 128)
    vp = -(-v // bc) * bc  # the vocabulary rounded up to whole chunks of the cross-entropy; the padding rows of the output matrix are zero and their logits are masked
    exact = vp == v and os.path.getsize(w("emb.f16")) == v * d * 2
    wlm = w("emb.f16") if exact else p("wlm.f16")
    if not exact:
        with open(wlm, "wb") as f:
            f.write(emb.tobytes())
            f.write(np.zeros((vp - v, d), dtype="<f2").tobytes())
    put(p("jrow"), np.arange(1, vp + 1))
    put(p("maskv"), np.where(np.arange(vp) < v, 0.0, -1e9))
    put(p("tgt"), R.next_targets(tokens).reshape(-1) + 1)
    for name, src in (("rope_q.chx", rope_source("rope_q", 1, True)), (f"rope_k.chx", rope_source("rope_k", grp, True)), (f"bias_v.chx", rope_source("bias_v", grp, False))):
        for old, new in tn.get("mutations", []):  # the tests build sessions with one deliberate bug in a generated kernel
            src = src.replace(old, new)
        open(p(name), "w").write(src)

    def kernel(name, **sched):
        src = next(q for q in (p(name), os.path.join(HERE, name), os.path.join(ROOT, "tests", "chx", "ported", name), os.path.join(ROOT, "tests", "chx", name)) if os.path.exists(q))
        if not sched:
            return src
        out = []
        for line in open(src).read().split("\n"):
            if line.startswith("schedule ") and "apple-m-series" in line:
                line = line.split("{")[0] + "{ " + " ".join(f"{k} {v_}" for k, v_ in sched.items()) + " }"
            out.append(line)
        dst = p(name.replace(".chx", "_" + "_".join(str(x) for x in sched.values()).replace(" ", "") + ".chx"))
        open(dst, "w").write("\n".join(out))
        return dst

    L = [f"# Qwen2 forward: {ll} layers, d {d}, {h} query heads over {hkv}, ff {ff}, vocabulary {v}, {nb} sequences of {t}"]
    prog = lambda name, kern, **kw: L.append(f"program {name} {kern} " + " ".join(f"{k}={v_}" for k, v_ in kw.items()))
    res = lambda target, path, flag="f32": L.append(f"resident {target} {path} {flag}")
    link = lambda a, b: L.append(f"link {a} -> {b}")
    gemm = lambda name, a, wfile, m, nn, kk: (prog(name, kernel("gemm_mma.chx", **tn["gemm_sched"].get((m, nn, kk), {})), m=m, n=nn, k=kk), link(a, f"{name}.a"), res(f"{name}.w", wfile, "f16"))
    eps = repr(c.eps if eps_override is None else eps_override)
    nbh = nb * h
    x_in = None
    xs = []
    for l in range(ll):
        s = str(l)
        q = f"l{l:02d}."
        prog("rm1_" + s, kernel("rms_h.chx"), r=n, c=d, bm=tn["ebm"], eps=eps)
        if x_in is None:
            res(f"rm1_{s}.x", p("x0"))
        else:
            link(x_in, f"rm1_{s}.x")
        res(f"rm1_{s}.gain", w(q + "ln1.f32"))
        gemm("qkv_" + s, f"rm1_{s}.y", w(q + "wqkv.f16"), n, d + 2 * dkv, d)
        for nm, kern, nh_, c0 in (("rq", "rope_q.chx", h, 0), ("rk", "rope_k.chx", hkv, d)):
            prog(f"{nm}_{s}", p(kern), nb=nb, nh=nh_, t=t, w=d + 2 * dkv, c0=c0, bm=tn["rbm"], hf=hf)
            link(f"qkv_{s}.y", f"{nm}_{s}.qkv")
            res(f"{nm}_{s}.bias", w(q + "bqkv.f32"))
            res(f"{nm}_{s}.cs", p("cos"))
            res(f"{nm}_{s}.sn", p("sin"))
        prog("rv_" + s, p("bias_v.chx"), nb=nb, nh=hkv, t=t, w=d + 2 * dkv, c0=d + dkv, bm=tn["rbm"], hf=hf)
        link(f"qkv_{s}.y", f"rv_{s}.qkv")
        res(f"rv_{s}.bias", w(q + "bqkv.f32"))
        prog("sc_" + s, kernel("att_s.chx", **tn["attn"]), nbh=nbh, t=t, dh=dh)
        link(f"rq_{s}.y", f"sc_{s}.q")
        link(f"rk_{s}.y", f"sc_{s}.k")
        prog("sm_" + s, kernel("att_sm.chx"), nbh=nbh, t=t, bm=tn["abm"], scale=repr(1.0 / math.sqrt(dh)))
        link(f"sc_{s}.s", f"sm_{s}.s")
        res(f"sm_{s}.mask", p("mask"))
        prog("ao_" + s, kernel("att_o.chx", **tn["ao"]), nbh=nbh, t=t, dh=dh)
        link(f"sm_{s}.p", f"ao_{s}.pr")
        link(f"rv_{s}.y", f"ao_{s}.v")
        prog("uh_" + s, kernel("unheads.chx"), nb=nb, nh=h, t=t, dh=dh, bm=tn["rbm"])
        link(f"ao_{s}.o", f"uh_{s}.o")
        gemm("wo_" + s, f"uh_{s}.y", w(q + "wo.f16"), n, d, d)
        prog("r1_" + s, kernel("res_add.chx"), r=n, c=d, bm=tn["ebm"])
        link(f"wo_{s}.y", f"r1_{s}.z")
        if x_in is None:
            res(f"r1_{s}.res", p("x0"))
        else:
            link(x_in, f"r1_{s}.res")
        prog("rm2_" + s, kernel("rms_h.chx"), r=n, c=d, bm=tn["ebm"], eps=eps)
        link(f"r1_{s}.y", f"rm2_{s}.x")
        res(f"rm2_{s}.gain", w(q + "ln2.f32"))
        gemm("gu_" + s, f"rm2_{s}.y", w(q + "wgu.f16"), n, 2 * ff, d)
        prog("sw_" + s, kernel("swiglu_h.chx"), r=n, f=ff, bm=tn["sbm"], bc=tn["sbc"])
        link(f"gu_{s}.y", f"sw_{s}.gu")
        gemm("dn_" + s, f"sw_{s}.y", w(q + "wd.f16"), n, d, ff)
        prog("r2_" + s, kernel("res_add.chx"), r=n, c=d, bm=tn["ebm"])
        link(f"dn_{s}.y", f"r2_{s}.z")
        link(f"r1_{s}.y", f"r2_{s}.res")
        x_in = f"r2_{s}.y"
        xs.append(x_in)
    prog("rmf", kernel("rms_h.chx"), r=n, c=d, bm=tn["ebm"], eps=eps)
    if x_in is None:
        res("rmf.x", p("x0"))
    else:
        link(x_in, "rmf.x")
    res("rmf.gain", w("norm.f32"))
    gemm("lm", "rmf.y", wlm, n, vp, d)
    nq = vp // bc
    prog("cs", kernel("ce_stats.chx"), r=n, c=vp, bc=bc, nq=nq)
    link("lm.y", "cs.lg")
    res("cs.tgt", p("tgt"))
    res("cs.jrow", p("jrow"))
    res("cs.maskv", p("maskv"))
    prog("cc", kernel("ce_comb.chx"), r=n, nq=nq, bm=tn["cbm"])
    for o in ("cm", "cs", "ct", "ci"):
        link(f"cs.{o}", f"cc.{o}")
    L.append("steps")
    L.append("answer cc.loss")
    L.append("answer cc.am")
    if acts:
        for x in xs:
            L.append(f"save {x} {os.path.abspath(acts)} f32")
    open(p("session"), "w").write("\n".join(L) + "\n")
    return p("session")


class Session:
    """A running metal (or CPU) session: `forward()` returns (per-position loss, 0-based arg max, seconds)."""

    def __init__(self, binary, session, extra=()):
        self.proc = subprocess.Popen([binary, session, *extra], stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)

    def ask(self, line):
        import time
        t0 = time.time()
        self.proc.stdin.write(line + "\n")
        self.proc.stdin.flush()
        out = self.proc.stdout.readline()
        if not out:
            raise SystemExit("session: " + self.proc.stderr.read()[:600])
        return out, time.time() - t0

    def forward(self, n):
        out, secs = self.ask("1")
        v = np.array(out.split(), dtype=np.float64)
        assert v.size == 2 * n, f"{v.size} numbers for {n} positions"
        return v[:n], v[n:].astype(np.int64) - 1, secs

    def checkpoint(self):
        return self.ask("checkpoint")[0].split()

    def close(self):
        self.proc.stdin.close()
        self.proc.wait()
        err = self.proc.stderr.read()
        return err


def read_acts(path, c):
    return np.fromfile(path, dtype="<f4").reshape(c.layers, c.n, c.d)


