#!/usr/bin/env python3
"""Writes so101_chain.py: the SO-101 chain from base_link to gripper_frame_link, read from the URDF that cancho-robot generates its kinematics from.

    python3 examples/weightspace/gen_chain.py /path/to/cancho-robot/tests/fixtures/urdf/so101_new_calib.urdf > examples/weightspace/so101_chain.py

The table is copied into this repository so that the harness and its tests need no other checkout; `check_fk.py` compares the numpy forward kinematics built on it with
cancho-robot's `src/kinematics.cho` (when that checkout is present). The numbers are the URDF's own strings, read as binary64."""
import hashlib
import sys
import xml.etree.ElementTree as ET

path = sys.argv[1]
raw = open(path, "rb").read()
root = ET.fromstring(raw)
joints = {j.find("child").get("link"): j for j in root.findall("joint")}
chain, link = [], "gripper_frame_link"
while link != "base_link":
    j = joints[link]
    chain.append(j)
    link = j.find("parent").get("link")
chain.reverse()
print('"""GENERATED by examples/weightspace/gen_chain.py from so101_new_calib.urdf (sha256 %s). Do not edit.' % hashlib.sha256(raw).hexdigest())
print()
print("The chain from base_link to gripper_frame_link: per joint (name, xyz, rpy, lower, upper), the limits in radians (None for the fixed last joint).")
print("A joint's frame is its parent's, moved by xyz, turned by R = Rz(yaw) Ry(pitch) Rx(roll), then turned about its own z axis by the joint angle.\"\"\"")
print()
print("CHAIN = [")
for j in chain:
    o = j.find("origin")
    xyz = [float(v) for v in o.get("xyz").split()]
    rpy = [float(v) for v in o.get("rpy").split()]
    lim = j.find("limit")
    lo, hi = (float(lim.get("lower")), float(lim.get("upper"))) if j.get("type") == "revolute" else (None, None)
    print("    (%r, %r, %r, %r, %r)," % (j.get("name"), tuple(xyz), tuple(rpy), lo, hi))
print("]")
