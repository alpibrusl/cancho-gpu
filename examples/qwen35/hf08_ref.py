#!/usr/bin/env python3
"""HF reference goldens for Qwen3.5-0.8B-Base and the published edit (docs/weight-space.md section 14, ticket T1; checks C3 to C6).

    python3 examples/qwen35/hf08_ref.py                      # writes golden/hf08/ (about an hour on a Mac CPU)
    python3 examples/qwen35/hf08_ref.py --check              # regenerates a small subset, compares with golden/hf08/ (minutes)

What it is. `transformers` 5.x on the CPU, text tower only (`Qwen3_5ForCausalLM`, built from `config.json`'s `text_config`, the weights
read from the checkpoint's `model.language_model.*` tensors; the vision tower and the `mtp.*` head are not loaded), run in two precisions:

  * float64: the installed modeling code recompiled with its float32 casts turned into float64 (`hf64.py`), weights widened from bf16.
    This is the REFERENCE: the numbers the cancho engine is held to (C3 to C6). It is a specification written from the mathematics
    through HF's own code, not what `transformers` ships.
  * float32: the shipped code as it is, with float32 weights (what a user of `transformers` on the CPU gets). The gap float32 -> float64
    is the FLOOR (14.6): no pass criterion on cancho's float32 kernels is tighter than what torch float32 itself achieves.

What is written, under golden/hf08/ (no tensor larger than a few KB; the large ones are named by sha256 and regenerated by this script):

  prompts.json         the 200 W1 prompts (examples/weightspace/w1_behave.py: GSM8K test problems 0..199, `build_question`, the model's own
                       chat template, `enable_thinking=True`, generation prompt added): sha256 of each rendered text, its token count
                       and the sha256 of its ids; the 8 check prompts (W1 problems 0, 1, 2 and 5 short fixed strings) in full, as ids.
  <model>.json         for `base` and `edited`:
    check.layers       per check prompt, per layer 0..23 (and the embedding and the final-norm output): max |x|, the L2 norm of every position
                       (so every position is checked, not a slice), the first 16 values of the first and of the last position, the sha256
                       of the float32 rounding of the whole [T, 1024] output, and, from the float32 run, the max |error| / max |reference|
                       (the floor), all float64 reference. Layers 3 (attention) and 15, 19 (the edited layers) are in the list like the rest.
    check.logits       the last-position logits of each check prompt: top-20 ids and values (float64 reference and float32), the sha256 of
                       the float32 rounding of the full 248,320 row, the max |float32 - float64| over the row (the C5 floor).
    argmax200          the greedy next token on the 200 W1 prompts, float64 (reference) and float32, the float64 top-2 gap, and the prompts
                       on which the two precisions disagree (each with both gaps). Empty is the expected answer; if it is not, it is listed.
    cont64             64-token greedy continuation of W1 prompts 0..19 (float64 reference, KV cache, EOS ignored so that 64 positions exist):
                       the 64 token ids, the top-5 ids and values of every step's logits (the teacher-forced check C7 compares these), the
                       first EOS position if any, and the float32 run's ids with the first position at which they differ.
  <model>_full.npz     the full float32-rounded outputs of the embedding and layers 0, 3, 15, 19, 23 for the shortest check prompt.

Determinism: single process, CPU only, `torch.use_deterministic_algorithms(True)`, no sampling, prompts one at a time (no padding), numbers
rounded to 10 significant digits when written. The sha256 of a float tensor is NOT promised to be portable across torch builds or thread
counts (a reduction order is not specified); the tolerances in tests/hf08.py are what is held, the hashes are for spotting a regeneration
that moved. The token ids and the argmax are exact.

Needs torch, transformers (>= 5.2), numpy, safetensors, pyarrow; the checkpoints (~/models/qwen35-08b-base, ~/models/qwen35-08b-edited) and
the GSM8K parquet (~/models/gsm8k/main/test-00000-of-00001.parquet). No GPU is used or looked for; no network."""
import argparse
import hashlib
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
DEFAULT_OUT = os.path.join(ROOT, "golden", "hf08")
HOME = os.path.expanduser("~")
MODELS = {"base": os.path.join(HOME, "models", "qwen35-08b-base"), "edited": os.path.join(HOME, "models", "qwen35-08b-edited")}
GSM8K = os.path.join(HOME, "models", "gsm8k", "main", "test-00000-of-00001.parquet")
N_W1 = 200            # W1 prompts: GSM8K test problems 0..199
CHECK_W1 = (0, 1, 2)  # of them, the three used in the layer-by-layer checks
N_CONT = 20           # problems 0..19 get the 64-token greedy continuation
CONT_LEN = 64
SHORT = ["The capital of France is", "def fib(n):\n    if n < 2:", "1 + 1 =", "Once upon a time, in a small village by the sea,",
         "<|im_start|>user\nHi<|im_end|>\n<|im_start|>assistant\n"]
FULL_LAYERS = (0, 3, 15, 19, 23)
TOPK_CHECK = 20
TOPK_CONT = 5
HEAD16 = 16
SIG = 10


def r(x):
    """A float rounded to SIG significant digits (the written number; keeps the files small and stable)."""
    return float(f"{float(x):.{SIG}g}")


def rl(xs):
    return [r(x) for x in xs]


def sha_f32(t):
    import numpy as np
    return hashlib.sha256(np.ascontiguousarray(t.detach().cpu().numpy().astype("float32")).tobytes()).hexdigest()


def sha_text(s):
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def sha_ids(ids):
    import numpy as np
    return hashlib.sha256(np.asarray(ids, dtype="<i8").tobytes()).hexdigest()


# ---------------------------------------------------------------- the model

def text_config_of(model_dir):
    with open(os.path.join(model_dir, "config.json"), encoding="utf-8") as f:
        return json.load(f)["text_config"]


def build_model(model_dir, prec):
    """The text tower of `model_dir` in `prec` ("f64": the float64 recompilation of HF's code, "f32": the code as shipped)."""
    import torch
    from safetensors import safe_open
    sys.path.insert(0, HERE)
    import hf64
    if prec == "f64":
        mod, dt = hf64.load(), torch.float64
    elif prec == "f32":
        import transformers.models.qwen3_5.modeling_qwen3_5 as mod
        dt = torch.float32
    else:
        raise ValueError(prec)
    tc = dict(text_config_of(model_dir))
    cfg = mod.Qwen3_5TextConfig(**{k: v for k, v in tc.items() if k != "model_type"})
    cfg._attn_implementation = "eager"
    old = torch.get_default_dtype()
    torch.set_default_dtype(dt)
    try:
        with torch.device("meta"):
            model = mod.Qwen3_5ForCausalLM(cfg)
    finally:
        torch.set_default_dtype(old)
    sd = {}
    index = os.path.join(model_dir, "model.safetensors.index.json")
    with open(index, encoding="utf-8") as f:
        files = sorted(set(json.load(f)["weight_map"].values()))
    for fn in files:
        with safe_open(os.path.join(model_dir, fn), framework="pt") as f:
            for k in f.keys():
                if k.startswith("model.language_model."):
                    sd["model." + k[len("model.language_model."):]] = f.get_tensor(k).to(dt)
                elif k == "lm_head.weight":
                    sd[k] = f.get_tensor(k).to(dt)
    missing, unexpected = model.load_state_dict(sd, strict=False, assign=True)
    if unexpected or [m for m in missing if m != "lm_head.weight"]:
        raise RuntimeError(f"{model_dir}: missing {missing}, unexpected {unexpected}")
    if "lm_head.weight" in missing:
        model.lm_head.weight = model.model.embed_tokens.weight  # tie_word_embeddings
    # buffers (rotary inverse frequencies) were created on the meta device: rebuild them on the CPU in `dt`
    model.model.rotary_emb = mod.Qwen3_5TextRotaryEmbedding(config=cfg)
    model.model.rotary_emb.to(dtype=dt)
    return model.eval()


# ---------------------------------------------------------------- one precision

def _out(o):
    return o[0] if isinstance(o, tuple) else o


def hidden_states(model, ids):
    """(embedding output, [layer outputs 0..L-1], final-norm output, last-position logits) for one prompt, each [T, H] float tensors."""
    import torch
    grabbed = {}
    hooks = []
    layers = model.model.layers

    def grab(name):
        def f(_m, _i, o):
            grabbed[name] = _out(o)[0].detach().clone()
        return f
    hooks.append(model.model.embed_tokens.register_forward_hook(grab("emb")))
    for i, l in enumerate(layers):
        hooks.append(l.register_forward_hook(grab(i)))
    hooks.append(model.model.norm.register_forward_hook(grab("norm")))
    try:
        with torch.no_grad():
            lg = model(torch.tensor([ids]), use_cache=False, logits_to_keep=1).logits[0, -1]
    finally:
        for h in hooks:
            h.remove()
    return grabbed["emb"], [grabbed[i] for i in range(len(layers))], grabbed["norm"], lg.detach()


def next_logits(model, ids):
    import torch
    with torch.no_grad():
        return model(torch.tensor([ids]), use_cache=False, logits_to_keep=1).logits[0, -1].detach()


def top_k(row, k):
    import torch
    v, i = torch.topk(row, k)
    return i.tolist(), v.tolist()


def greedy(model, ids, n):
    """n greedy tokens with the KV/state cache, EOS ignored: (token ids, per-step top-k ids and values)."""
    import torch
    out, tops = [], []
    with torch.no_grad():
        o = model(torch.tensor([ids]), use_cache=True, logits_to_keep=1)
        for _ in range(n):
            row = o.logits[0, -1]
            ti, tv = top_k(row, TOPK_CONT)
            tops.append((ti, tv))
            t = int(torch.argmax(row))
            out.append(t)
            o = model(torch.tensor([[t]]), past_key_values=o.past_key_values, use_cache=True)
    return out, tops


def run_precision(model, spec, progress=None):
    """Everything for one precision: the check prompts' hidden states, the 1-token argmax and gap of `many`, the greedy continuations."""
    res = {"check": [], "argmax": [], "gap": [], "cont": []}
    for n, ids in enumerate(spec["check"]):
        emb, layers, normed, lg = hidden_states(model, ids)
        res["check"].append({"emb": emb, "layers": layers, "norm": normed, "logits": lg})
        if progress:
            progress(f"check {n + 1}/{len(spec['check'])}")
    for n, ids in enumerate(spec["many"]):
        row = next_logits(model, ids)
        ti, tv = top_k(row, 2)
        res["argmax"].append(ti[0])
        res["gap"].append(tv[0] - tv[1])
        if progress and n % 20 == 19:
            progress(f"argmax {n + 1}/{len(spec['many'])}")
    for n, ids in enumerate(spec["cont"]):
        res["cont"].append(greedy(model, ids, spec["cont_len"]))
        if progress:
            progress(f"cont {n + 1}/{len(spec['cont'])}")
    return res


def rel_err(a, b):
    return float((a - b).abs().max() / b.abs().max().clamp_min(1e-300))


def assemble(ref, f32, spec):
    """The golden dictionary of one model from its float64 (`ref`) and float32 (`f32`) results."""
    import numpy as np
    layers = []
    full = {}
    short = min(range(len(spec["check"])), key=lambda i: len(spec["check"][i]))
    for p, (a, b) in enumerate(zip(ref["check"], f32["check"])):
        entry = {"n_tokens": len(spec["check"][p]), "outputs": []}
        names = ["emb"] + list(range(len(a["layers"]))) + ["norm"]
        for nm in names:
            x = a[nm] if nm in ("emb", "norm") else a["layers"][nm]
            y = b[nm] if nm in ("emb", "norm") else b["layers"][nm]
            entry["outputs"].append({
                "at": nm, "max_abs": r(x.abs().max()), "norms": rl(x.norm(dim=-1).tolist()),
                "first_pos_head": rl(x[0, :HEAD16].tolist()), "last_pos_head": rl(x[-1, :HEAD16].tolist()),
                "sha256_f32": sha_f32(x), "floor_rel": r(rel_err(y.double(), x))})
            if p == short and (nm == "emb" or nm in FULL_LAYERS):
                full[f"{nm}"] = x.float().numpy()
        layers.append(entry)
    logits = []
    for p, (a, b) in enumerate(zip(ref["check"], f32["check"])):
        ti, tv = top_k(a["logits"], TOPK_CHECK)
        fi, fv = top_k(b["logits"], TOPK_CHECK)
        logits.append({"top20_ids": ti, "top20_vals": rl(tv), "f32_top20_ids": fi, "f32_top20_vals": rl(fv),
                       "row_sha256_f32": sha_f32(a["logits"]), "row_size": int(a["logits"].numel()),
                       "floor_abs": r((b["logits"].double() - a["logits"]).abs().max())})
    dis = [{"index": i, "f64": a, "f32": b, "gap_f64": r(g)} for i, (a, b, g) in enumerate(zip(ref["argmax"], f32["argmax"], ref["gap"])) if a != b]
    cont = []
    for (ids, tops), (ids32, _t32) in zip(ref["cont"], f32["cont"]):
        first = next((i for i, (x, y) in enumerate(zip(ids, ids32)) if x != y), None)
        cont.append({"ids": ids, "top5_ids": [t[0] for t in tops], "top5_vals": [rl(t[1]) for t in tops],
                     "first_eos": next((i for i, t in enumerate(ids) if t in spec["eos"]), None),
                     "f32_ids": ids32, "f32_first_difference": first})
    per_layer_floor = [r(max(e["outputs"][k]["floor_rel"] for e in layers)) for k in range(len(layers[0]["outputs"]))]
    return {
        "check": {"layers": layers, "logits": logits, "floor_rel_max_per_output": per_layer_floor},
        "argmax200": {"f64": ref["argmax"], "f32": f32["argmax"], "gap_f64": rl(ref["gap"]), "disagree": dis,
                      "min_gap_f64": r(min(ref["gap"])) if ref["gap"] else None},
        "cont64": cont,
    }, full


def compute_model(load, spec, progress=None):
    """load(prec) -> model. Returns (golden dict, full arrays). The float64 pass first, then the float32 one."""
    t0 = time.time()
    m = load("f64")
    ref = run_precision(m, spec, (lambda s: progress("f64 " + s + f" [{time.time() - t0:.0f}s]")) if progress else None)
    del m
    m = load("f32")
    f32 = run_precision(m, spec, (lambda s: progress("f32 " + s + f" [{time.time() - t0:.0f}s]")) if progress else None)
    del m
    return assemble(ref, f32, spec)


# ---------------------------------------------------------------- prompts

def render_prompts(model_dir, parquet, n):
    """The W1 prompts as w1_behave.transformers_generator renders them: [(text, ids)] for GSM8K problems 0..n-1."""
    sys.path.insert(0, os.path.join(ROOT, "examples", "weightspace"))
    import w1_behave as B
    import transformers as T
    tok = T.AutoTokenizer.from_pretrained(model_dir)
    probs = B.load_problems(parquet, n)
    out = []
    for p in probs:
        text = tok.apply_chat_template([{"role": "user", "content": B.build_question(p["question"])}], tokenize=False,
                                       add_generation_prompt=True, enable_thinking=True)
        out.append((text, tok(text, add_special_tokens=False)["input_ids"]))
    short = [tok(s, add_special_tokens=False)["input_ids"] for s in SHORT]
    return out, short, sorted({tok.eos_token_id, 248044, 248046} - {None})


def make_spec(model_dir, parquet, n, n_cont, cont_len):
    w1, short, eos = render_prompts(model_dir, parquet, n)
    check = [w1[i][1] for i in CHECK_W1 if i < n] + short
    return {"w1": w1, "short": short, "eos": eos, "check": check, "many": [i for _t, i in w1],
            "cont": [i for _t, i in w1[:n_cont]], "cont_len": cont_len}


def prompts_golden(spec):
    return {"w1": [{"index": i, "sha256_text": sha_text(t), "n_tokens": len(ids), "sha256_ids": sha_ids(ids)} for i, (t, ids) in enumerate(spec["w1"])],
            "check": [{"index": i, "ids": ids} for i, ids in enumerate(spec["check"])], "check_w1_problems": list(CHECK_W1),
            "short_prompts": SHORT, "eos": spec["eos"], "n_cont": len(spec["cont"]), "cont_len": spec["cont_len"],
            "template": "tokenizer.apply_chat_template([{role: user, content: build_question(q)}], add_generation_prompt=True, enable_thinking=True)"}


# ---------------------------------------------------------------- files

def dumps(d):
    """One top-level key a line, everything else compact: small files whose diffs can be read."""
    return "{\n" + ",\n".join(json.dumps(k) + ":" + json.dumps(v, separators=(",", ":")) for k, v in d.items()) + "\n}\n"


def write(out, name, text):
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, name), "w", encoding="utf-8") as f:
        f.write(text)


def versions():
    import numpy
    import torch
    import transformers
    return {"torch": torch.__version__, "transformers": transformers.__version__, "numpy": numpy.__version__, "threads": torch.get_num_threads()}


_conv1d = None


def depthwise_conv1d(x, w, b=None, stride=1, padding=0, dilation=1, groups=1):
    """F.conv1d for the depthwise case (groups == channels, stride and dilation 1), as a sum of K shifted products. torch's CPU kernel for
    grouped convolutions runs one tiny convolution a group (110,592 calls and 2.4 s a decoded token on this model); the sum is the same
    mathematics, rounded in a different order (tests/hf08.py holds the two to 1e-14 in float64). Anything else goes to torch."""
    import torch
    if _conv1d is None or groups != x.shape[1] or groups == 1 or stride != 1 or dilation != 1 or w.shape[1] != 1 or isinstance(padding, str):
        return _conv1d(x, w, b, stride, padding, dilation, groups)
    pad = padding[0] if isinstance(padding, (tuple, list)) else padding
    if pad:
        x = torch.nn.functional.pad(x, (pad, pad))
    k, n = w.shape[2], x.shape[2] - w.shape[2] + 1
    out = w[None, :, 0, 0, None] * x[:, :, 0:n]
    for j in range(1, k):
        out = out + w[None, :, 0, j, None] * x[:, :, j:j + n]
    return out if b is None else out + b[None, :, None]


def setup(threads, fast_conv=True):
    import torch
    global _conv1d
    if fast_conv and _conv1d is None:
        _conv1d = torch.nn.functional.conv1d
        torch.nn.functional.conv1d = depthwise_conv1d
    if threads:
        torch.set_num_threads(threads)
    torch.use_deterministic_algorithms(True)
    torch.manual_seed(0)


def generate(a):
    import numpy as np
    setup(a.threads)
    spec = make_spec(MODELS["base"], a.gsm8k, a.n, a.cont, CONT_LEN)
    for name in a.models:  # the same prompts for both checkpoints, or a template that differs is a finding
        s2 = make_spec(MODELS[name], a.gsm8k, a.n, a.cont, CONT_LEN)
        if s2["many"] != spec["many"] or s2["w1"] != spec["w1"]:
            sys.exit(f"{name}: the rendered prompts differ from the base's")
    write(a.out, "prompts.json", dumps(prompts_golden(spec)))
    for name in a.models:
        t0 = time.time()
        gold, full = compute_model(lambda prec, d=MODELS[name]: build_model(d, prec), spec, lambda s, n=name: print(f"{n}: {s}", flush=True))
        meta = {"model": name, "dir": os.path.basename(MODELS[name]), "versions": versions(),
                "precision": {"reference": "float64 (hf64.py: HF's code recompiled with float64 casts), weights widened from bf16",
                              "floor": "float32 (the code as shipped), weights widened from bf16"},
                "command": "python3 examples/qwen35/hf08_ref.py"}
        write(a.out, name + ".json", dumps({"meta": meta, **gold}))
        np.savez(os.path.join(a.out, name + "_full.npz"), **full)
        d = gold["argmax200"]["disagree"]
        print(f"{name}: done in {time.time() - t0:.0f}s; f32 vs f64 argmax disagreements on {len(d)} of {len(spec['many'])}: {d}", flush=True)


def close(x, y, tol):
    return abs(x - y) <= tol * max(1.0, abs(y))


def check(a):
    """Regenerate a subset (3 check prompts + 2 short, `--n` argmax prompts, one continuation of 8 tokens) and compare with the committed goldens."""
    setup(a.threads)
    spec = make_spec(MODELS["base"], a.gsm8k, N_W1, 1, 8)
    spec["many"] = spec["many"][:a.n]
    bad = 0
    with open(os.path.join(a.out, "prompts.json"), encoding="utf-8") as f:
        pg = json.load(f)
    for i, w in enumerate(spec["w1"]):
        g = pg["w1"][i]
        if (sha_text(w[0]), len(w[1]), sha_ids(w[1])) != (g["sha256_text"], g["n_tokens"], g["sha256_ids"]):
            print(f"FAIL prompt {i} differs from the golden")
            bad += 1
    for name in a.models:
        with open(os.path.join(a.out, name + ".json"), encoding="utf-8") as f:
            g = json.load(f)
        m = build_model(MODELS[name], "f64")
        sub = {"check": spec["check"][:1] + spec["check"][3:4], "many": spec["many"], "cont": spec["cont"], "cont_len": 8}
        res = run_precision(m, sub)
        for ci, gi in ((0, 0), (1, 3)):
            got = res["check"][ci]
            for k, o in enumerate(["emb"] + list(range(24)) + ["norm"]):
                x = got[o] if o in ("emb", "norm") else got["layers"][o]
                want = g["check"]["layers"][gi]["outputs"][k]
                ok = close(float(x.abs().max()), want["max_abs"], 1e-7) and all(close(u, v, 1e-6) for u, v in zip(x.norm(dim=-1).tolist(), want["norms"]))
                if not ok:
                    print(f"FAIL {name} check prompt {gi} output {o}")
                    bad += 1
            ti, tv = top_k(got["logits"], TOPK_CHECK)
            if ti != g["check"]["logits"][gi]["top20_ids"] or not all(close(u, v, 1e-7) for u, v in zip(tv, g["check"]["logits"][gi]["top20_vals"])):
                print(f"FAIL {name} check prompt {gi} logits")
                bad += 1
        if res["argmax"] != g["argmax200"]["f64"][:len(res["argmax"])]:
            print(f"FAIL {name} argmax")
            bad += 1
        ids, tops = res["cont"][0]
        if ids != g["cont64"][0]["ids"][:8] or not all(close(u, v, 1e-7) for t, w in zip(tops, g["cont64"][0]["top5_vals"]) for u, v in zip(t[1], w)):
            print(f"FAIL {name} continuation")
            bad += 1
        print(f"{name}: checked")
    print("hf08_ref --check:", "FAILED" if bad else "ok")
    return 1 if bad else 0


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--out", default=DEFAULT_OUT)
    p.add_argument("--gsm8k", default=GSM8K)
    p.add_argument("--models", nargs="+", default=["base", "edited"], choices=sorted(MODELS))
    p.add_argument("--n", type=int, default=N_W1, help="W1 prompts for the argmax golden (200)")
    p.add_argument("--cont", type=int, default=N_CONT, help="prompts for the 64-token continuation (20)")
    p.add_argument("--threads", type=int, default=0)
    p.add_argument("--check", action="store_true", help="regenerate a subset and compare with the committed goldens")
    a = p.parse_args(argv)
    for d in [MODELS[m] for m in a.models] + [a.gsm8k]:
        if not os.path.exists(d):
            print(f"missing: {d}")
            return 2
    if a.check:
        if a.n == N_W1:
            a.n = 6
        return check(a)
    generate(a)
    return 0


if __name__ == "__main__":
    sys.exit(main())
