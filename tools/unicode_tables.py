#!/usr/bin/env python3
"""Generates src/unicode_data.cho from Python's `unicodedata` (docs/runtime.md section 9, docs/native.md N2f).

    unicode_tables.py > src/unicode_data.cho        # scripts/regen-unicode-data.sh

The tables are the ones the Qwen tokenizers' regexes name and NFC needs, from the Unicode Character Database that this Python
carries (`unicodedata.unidata_version`, printed in the header):

  letter      \\p{L}   the general categories Lu Ll Lt Lm Lo
  mark        \\p{M}   Mn Mc Me
  numeric     \\p{N}   Nd Nl No
  whitespace  White_Space (\\s in the regexes): a fixed list of 25 scalar values, stable since Unicode 6.3
  ccc         canonical combining classes, the scalar values whose class is not 0
  comp        canonical compositions (first, second, composite): the pairs of a canonical two-scalar decomposition that NFC composes
              (so composition exclusions and non-starter decompositions are left out)
  decomp_index / decomp_data
              the full canonical decomposition of every scalar value that has one, singletons included (U+2126 OHM SIGN
              decomposes to U+03A9), except the Hangul syllables, which are arithmetic

It replaced `tools/unicode_tables.rs`, which printed Rust's `char::is_alphabetic` / `is_numeric` / `is_whitespace` (the Alphabetic
property, which includes marks such as the Thai vowels) and lex-rt's NFC tables, which had no decompositions.
"""
import sys
import unicodedata as ud

WHITE_SPACE = [(0x09, 0x0D), (0x20, 0x20), (0x85, 0x85), (0xA0, 0xA0), (0x1680, 0x1680), (0x2000, 0x200A), (0x2028, 0x2029),
               (0x202F, 0x202F), (0x205F, 0x205F), (0x3000, 0x3000)]
SCALARS = [c for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF]


def ranges(pred):
    out, lo = [], None
    for c in range(0x110000):
        hit = pred(c)
        if hit and lo is None:
            lo = c
        elif not hit and lo is not None:
            out += [lo, c - 1]
            lo = None
    if lo is not None:
        out += [lo, 0x10FFFF]
    return out


def table(name, what, words):
    print(f"// {what}")
    print(f"static {name}_table: [int] {{")
    print(f"    let t = alloc_slice[static]({len(words)}, 0);")
    print("    var at = 0;")
    for n in range(0, max(len(words), 1), 200):
        chunk = words[n:n + 200]
        k = n // 200
        print(f'    let chunk{k} = "{"".join("%06x" % w for w in chunk)}";')
        print(f"    var i{k} = 0;")
        print(f"    while i{k} < len(chunk{k}) / 6 {{")
        print(f"        t[at + i{k}] = number(chunk{k}, i{k});")
        print(f"        i{k} = i{k} + 1;")
        print("    }")
        print(f"    at = at + len(chunk{k}) / 6;")
    print("    return t;")
    print("}")
    print()
    print(f"pub fn {name}() -> [] &static [int] {{")
    print(f"    return {name}_table;")
    print("}")
    print()


def is_hangul_syllable(c):
    return 0xAC00 <= c <= 0xD7A3


def main():
    cat = lambda c: ud.category(chr(c))
    ws = set()
    for lo, hi in WHITE_SPACE:
        ws.update(range(lo, hi + 1))
    ccc = []
    comp = []
    index, data = [], []
    for c in SCALARS:
        k = ud.combining(chr(c))
        if k:
            ccc += [c, k]
        d = ud.decomposition(chr(c))
        if d and not d.startswith("<"):  # a canonical (untagged) mapping
            parts = [int(x, 16) for x in d.split()]
            if len(parts) == 2 and ud.normalize("NFC", chr(parts[0]) + chr(parts[1])) == chr(c):
                comp += [parts[0], parts[1], c]
        full = ud.normalize("NFD", chr(c))
        if full != chr(c) and not is_hangul_syllable(c):
            index += [c, len(data), len(full)]
            data += [ord(x) for x in full]
    triples = sorted((comp[i], comp[i + 1], comp[i + 2]) for i in range(0, len(comp), 3))
    comp = [x for t in triples for x in t]

    print("edition 5;")
    print("module unicode_data;")
    print()
    print("// GENERATED by scripts/regen-unicode-data.sh from tools/unicode_tables.py")
    print(f"// with Python's unicodedata, Unicode {ud.unidata_version}; do not edit (docs/runtime.md section 9).")
    print("//")
    print("// Every number is six hex digits. A range table is `lo hi lo hi ...`, both ends included; `ccc` is `scalar class ...`;")
    print("// `comp` is `first second composite ...`, sorted by (first, second); `decomp_index` is `scalar offset length ...`, sorted by")
    print("// scalar, into `decomp_data`, the scalar values of the full canonical decomposition.")
    print()
    print("fn hex_digit(c: int) -> [] int {")
    print("    if c >= 97 {")
    print("        return c - 87;")
    print("    }")
    print("    return c - 48;")
    print("}")
    print()
    print("// The `i`th six-digit number of `s`.")
    print("fn number(s: &static [byte], i: int) -> [] int {")
    print("    var v = 0;")
    print("    var k = 0;")
    print("    while k < 6 {")
    print("        v = v * 16 + hex_digit(int_of(s[i * 6 + k]));")
    print("        k = k + 1;")
    print("    }")
    print("    return v;")
    print("}")
    print()
    table("letter", "General category L* (Unicode \\p{L}).", ranges(lambda c: cat(c)[0] == "L" and not 0xD800 <= c <= 0xDFFF))
    table("mark", "General category M* (Unicode \\p{M}).", ranges(lambda c: cat(c)[0] == "M"))
    table("numeric", "General category N* (Unicode \\p{N}).", ranges(lambda c: cat(c)[0] == "N"))
    table("whitespace", "White_Space (Unicode \\s).", ranges(lambda c: c in ws))
    table("ccc", "Canonical combining classes other than 0.", ccc)
    table("comp", "Canonical compositions (first, second, composite).", comp)
    table("decomp_index", "Canonical decompositions: scalar, offset into decomp_data, length.", index)
    table("decomp_data", "The scalar values of the canonical decompositions.", data)


if __name__ == "__main__":
    import contextlib
    import io

    buffer = io.StringIO()
    with contextlib.redirect_stdout(buffer):
        main()
    sys.stdout.write(buffer.getvalue().rstrip("\n") + "\n")  # no trailing blank line: the formatter's rule
