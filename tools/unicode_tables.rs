//! The Unicode tables of `src/unicode_data.cho`, printed as cancho source
//! from the very predicates and tables the oracle uses (docs/runtime.md §9).
//!
//! It is not part of lex-gpu: `scripts/regen-unicode-data.sh` copies it into
//! `crates/lex-rt/examples/` for the build and removes it after.
//!
//!     unicode_tables > src/unicode_data.cho
//!
//! The ranges are where `char::is_alphabetic`, `is_numeric` and
//! `is_whitespace` of the Rust that builds this are true, over every
//! scalar value; CCC and COMP are lex-rt's own NFC tables.

use lex_rt::nfc_table::{CCC, COMP};

fn ranges(f: impl Fn(char) -> bool) -> Vec<u32> {
    let mut out = vec![];
    let mut open: Option<u32> = None;
    for cp in 0..=0x10FFFFu32 {
        let hit = char::from_u32(cp).is_some_and(&f);
        match (hit, open) {
            (true, None) => open = Some(cp),
            (false, Some(lo)) => {
                out.push(lo);
                out.push(cp - 1);
                open = None;
            }
            _ => {}
        }
    }
    if let Some(lo) = open {
        out.push(lo);
        out.push(0x10FFFF);
    }
    out
}

fn table(name: &str, what: &str, words: &[u32]) {
    println!("// {what}");
    println!("static {name}_table: [int] {{");
    println!("    let t = alloc_slice[static]({}, 0);", words.len());
    println!("    var at = 0;");
    for (n, chunk) in words.chunks(200).enumerate() {
        let hex: String = chunk.iter().map(|w| format!("{w:06x}")).collect();
        println!("    let chunk{n} = \"{hex}\";");
        println!("    var i{n} = 0;");
        println!("    while i{n} < len(chunk{n}) / 6 {{");
        println!("        t[at + i{n}] = number(chunk{n}, i{n});");
        println!("        i{n} = i{n} + 1;");
        println!("    }}");
        println!("    at = at + len(chunk{n}) / 6;");
    }
    println!("    return t;");
    println!("}}");
    println!();
    println!("pub fn {name}() -> [] &static [int] {{");
    println!("    return {name}_table;");
    println!("}}");
    println!();
}

fn main() {
    println!("edition 5;");
    println!("module unicode_data;");
    println!();
    println!("// GENERATED by scripts/regen-unicode-data.sh from tools/unicode_tables.rs");
    println!("// with rustc {}; do not edit (docs/runtime.md §9).", env!("RUSTC_VERSION"));
    println!("//");
    println!("// Every number is six hex digits. A range table is `lo hi lo hi ...`,");
    println!("// both ends included; `ccc` is `scalar class ...`; `comp` is `first");
    println!("// second composite ...`, sorted by (first, second).");
    println!();
    println!("fn hex_digit(c: int) -> [] int {{");
    println!("    if c >= 97 {{");
    println!("        return c - 87;");
    println!("    }}");
    println!("    return c - 48;");
    println!("}}");
    println!();
    println!("// The `i`th six-digit number of `s`.");
    println!("fn number(s: &static [byte], i: int) -> [] int {{");
    println!("    var v = 0;");
    println!("    var k = 0;");
    println!("    while k < 6 {{");
    println!("        v = v * 16 + hex_digit(int_of(s[i * 6 + k]));");
    println!("        k = k + 1;");
    println!("    }}");
    println!("    return v;");
    println!("}}");
    println!();
    table("alphabetic", "Alphabetic, as Rust's `char::is_alphabetic`.", &ranges(char::is_alphabetic));
    table("numeric", "N*, as Rust's `char::is_numeric`.", &ranges(char::is_numeric));
    table("whitespace", "White_Space, as Rust's `char::is_whitespace`.", &ranges(char::is_whitespace));
    let ccc: Vec<u32> = CCC.iter().flat_map(|&(c, k)| [c, k as u32]).collect();
    table("ccc", "Canonical combining classes, from lex-rt's `nfc_table::CCC`.", &ccc);
    let comp: Vec<u32> = COMP.iter().flat_map(|&(a, b, c)| [a, b, c]).collect();
    table("comp", "Canonical compositions, from lex-rt's `nfc_table::COMP`.", &comp);
}
