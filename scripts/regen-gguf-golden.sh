#!/bin/sh
# Regenerate golden/gguf/ with the independent Python reader: for every fixture of tests/gguf/*.gguf, the dump
# tools/gguf_dump.py prints (with --sum). Needs python3 and nothing else.
#
#     scripts/regen-gguf-golden.sh
#
# The goldens were first made by lex-rt's Rust reader (golden/gguf/PROVENANCE); tools/gguf_dump.py reproduces them byte for
# byte (tests/oracles.py), so regenerating changes nothing. docs/native.md N2f.
set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd)
for f in "$ROOT"/tests/gguf/*.gguf; do
  python3 "$ROOT/tools/gguf_dump.py" "$f" --sum > "$ROOT/golden/gguf/$(basename "$f" .gguf).txt"
done
echo "golden/gguf/ regenerated by tools/gguf_dump.py"
